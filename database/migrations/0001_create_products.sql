CREATE TABLE IF NOT EXISTS products (
    id INT UNSIGNED NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(100) NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    discount_percentage DECIMAL(5, 2) NOT NULL,
    rating DECIMAL(3, 2) NOT NULL,
    stock INT UNSIGNED NOT NULL,
    brand VARCHAR(255) NULL,
    sku VARCHAR(64) NOT NULL,
    weight DECIMAL(10, 2) NOT NULL,
    width DECIMAL(10, 2) NOT NULL,
    height DECIMAL(10, 2) NOT NULL,
    depth DECIMAL(10, 2) NOT NULL,
    warranty_information VARCHAR(255) NOT NULL,
    shipping_information VARCHAR(255) NOT NULL,
    availability_status VARCHAR(20) NOT NULL,
    return_policy VARCHAR(255) NOT NULL,
    minimum_order_quantity INT UNSIGNED NOT NULL,
    barcode VARCHAR(64) NOT NULL,
    qr_code_url VARCHAR(2048) NOT NULL,
    thumbnail_url VARCHAR(2048) NOT NULL,
    source_created_at DATETIME(3) NOT NULL,
    source_updated_at DATETIME(3) NOT NULL,
    imported_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
